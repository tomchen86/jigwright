import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath, pathToFileURL } from 'node:url';
import { resolveGovernanceSourceAlias } from '../packages/workflow-engine/src/composition-root/governance-sources-production.ts';

/** Package purpose sentences from the owner baseline in the Source ledger. */
export function renderAgentRuleSources(sourceText: string): string {
  const purpose = sourceText
    .split('### Product purpose\n')[1]
    ?.split('### Trust model')[0];
  if (!purpose) throw new Error('R-000 product purpose is missing.');
  const paragraphs = purpose
    .trim()
    .split(/\n\s*\n/u)
    .map((paragraph) => paragraph.replace(/\n/gu, ' '));
  const selected = paragraphs.filter(
    (paragraph) =>
      paragraph.startsWith('Jigwright is ') ||
      paragraph.startsWith('Security governance is '),
  );
  if (selected.length !== 2)
    throw new Error(
      'R-000 purpose paragraphs changed; review the guidance source selection.',
    );
  const sentences = selected.map((paragraph) =>
    paragraph.slice(0, paragraph.indexOf('.') + 1),
  );
  const literal = JSON.stringify(sentences.join(' '));
  return `/**
 * Packages selected R-000 purpose sentences for generated agent guidance.
 *
 * Invariants:
 * - Generation requires exactly two matching R-000 purpose paragraphs.
 */
// Generated by scripts/generate-agent-rule-sources.ts from the Source ledger R-000 alias.
// prettier-ignore
export const R000_PRODUCT_PURPOSE =
  ${literal};
`;
}

if (
  process.argv[1] &&
  import.meta.url === pathToFileURL(process.argv[1]).href
) {
  const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
  const target = path.join(
    root,
    'packages/workflow-engine/src/modules/guidance/catalog/agent-rule-sources.ts',
  );
  const expected = renderAgentRuleSources(
    resolveGovernanceSourceAlias(root, 'R-000')
      .map((source) => source.text)
      .join('\n\n'),
  );
  if (process.argv.includes('--check')) {
    if (fs.readFileSync(target, 'utf8') !== expected)
      throw new Error('Agent rule sources are stale.');
  } else fs.writeFileSync(target, expected);
}
