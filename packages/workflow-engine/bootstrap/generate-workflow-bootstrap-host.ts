/** Generate engine source first, then this pinned ordinary host, then independent recovery and protected artifacts. */
import fs from 'node:fs';
import path from 'node:path';
import ts from 'typescript';
import {
  replaceFile,
  requireContainedDirectory,
} from './closure-generation-files.ts';
import { readClosureFile } from './control-plane-bootstrap-files.ts';
import { rawDigest } from './control-plane-bootstrap-values.ts';
import { generateBuiltInEngineClosure } from './generate-built-in-engine-closure.ts';
import {
  WORKFLOW_BOOTSTRAP_HOST_ENTRYPOINT,
  WORKFLOW_BOOTSTRAP_HOST_MANIFEST_PATH,
  WORKFLOW_BOOTSTRAP_HOST_PIN_PATH,
  workflowBootstrapHostPaths,
  type WorkflowBootstrapHostManifest,
} from './workflow-bootstrap-host.ts';

const DEFAULT_REPOSITORY_ROOT = path.resolve(import.meta.dirname, '../../..');
export type WorkflowBootstrapHostGenerationMode = '--check' | '--write';

export function renderWorkflowBootstrapHost(repositoryRoot: string) {
  const root = fs.realpathSync(repositoryRoot);
  const packageRoot = requireContainedDirectory(root, [
    'packages',
    'workflow-engine',
  ]);
  requireContainedDirectory(packageRoot, ['bootstrap']);
  const engine = generateBuiltInEngineClosure(root, '--check');
  const engineBytes = readClosureFile(
    path.join(packageRoot, 'bootstrap/built-in-engine-closure.json'),
    0o644,
  );
  const enginePin = readClosureFile(
    path.join(packageRoot, 'bootstrap/built-in-engine-closure-pin.ts'),
    0o644,
  ).toString('utf8');
  if (
    engineBytes.toString('utf8') !== engine.manifestBytes ||
    enginePin !== engine.pinSource
  )
    throw new Error(
      'Generate the built-in engine closure before the workflow bootstrap host.',
    );
  const engineManifestDigest = engine.manifestDigest;
  const engineManifest = engine.manifest;
  const inventory = workflowBootstrapHostPaths();
  const files = inventory.map((relative) => {
    const absolute = path.join(packageRoot, relative);
    const stats = fs.lstatSync(absolute, { throwIfNoEntry: false });
    const mode = (stats?.mode ?? 0) & 0o777;
    if (mode !== 0o644 && mode !== 0o755)
      throw new Error(`Unsafe workflow bootstrap host mode: ${relative}`);
    const bytes = readClosureFile(absolute, mode);
    assertCompleteBootstrapImports(
      relative,
      bytes.toString('utf8'),
      inventory,
      engineManifest.files.map((entry) => entry.path),
    );
    return Object.freeze({
      path: relative,
      mode: mode === 0o755 ? ('100755' as const) : ('100644' as const),
      digest: rawDigest(bytes),
    });
  });
  const manifest: WorkflowBootstrapHostManifest = Object.freeze({
    kind: 'workflow-bootstrap-host.v1',
    entrypoint: WORKFLOW_BOOTSTRAP_HOST_ENTRYPOINT,
    engineManifestDigest,
    files: Object.freeze(files),
  });
  const manifestBytes = `${JSON.stringify(manifest, null, 2)}\n`;
  const manifestDigest = rawDigest(manifestBytes);
  const pinSource = `// Generated by generate-workflow-bootstrap-host.ts --write.\nexport const WORKFLOW_BOOTSTRAP_HOST_MANIFEST_DIGEST =\n  '${manifestDigest}' as const;\n`;
  return Object.freeze({ manifest, manifestBytes, manifestDigest, pinSource });
}

export function generateWorkflowBootstrapHost(
  repositoryRoot: string,
  mode: WorkflowBootstrapHostGenerationMode,
) {
  assertMode(mode);
  const root = fs.realpathSync(repositoryRoot);
  const rendered = renderWorkflowBootstrapHost(root);
  const packageRoot = path.join(root, 'packages/workflow-engine');
  for (const [relative, bytes] of [
    [WORKFLOW_BOOTSTRAP_HOST_MANIFEST_PATH, rendered.manifestBytes],
    [WORKFLOW_BOOTSTRAP_HOST_PIN_PATH, rendered.pinSource],
  ] as const) {
    const absolute = path.join(packageRoot, relative);
    if (mode === '--write') replaceFile(absolute, bytes);
    else if (readClosureFile(absolute, 0o644).toString('utf8') !== bytes)
      throw new Error(
        'Workflow bootstrap host metadata is stale; run generate-workflow-bootstrap-host.ts --write.',
      );
  }
  return rendered;
}

/** Every literal import/export/type dependency must resolve inside the host or separately pinned engine inventory. */
function assertCompleteBootstrapImports(
  filePath: string,
  source: string,
  hostPaths: readonly string[],
  enginePaths: readonly string[],
): void {
  const parsed = ts.createSourceFile(
    filePath,
    source,
    ts.ScriptTarget.Latest,
    true,
    ts.ScriptKind.TS,
  );
  const validate = (specifier: string): void => {
    // Ordinary hosts use ESM imports. Loader factories are outside this
    // inventory scanner's supported source contract; recovery generation is separate.
    if (specifier === 'node:module') {
      throw new Error(
        `Unsupported bootstrap import loader: ${filePath} -> ${specifier}`,
      );
    }
    if (specifier.startsWith('node:')) return;
    if (!specifier.startsWith('.'))
      throw new Error(
        `Uninventoried bootstrap import: ${filePath} -> ${specifier}`,
      );
    const resolved = path.posix.normalize(
      path.posix.join(path.posix.dirname(filePath), specifier),
    );
    if (
      !hostPaths.includes(resolved) &&
      !(resolved.startsWith('src/') && enginePaths.includes(resolved))
    )
      throw new Error(
        `Uninventoried bootstrap import: ${filePath} -> ${specifier}`,
      );
  };
  const visit = (node: ts.Node): void => {
    // Reject the CommonJS loader itself, including aliases, parentheses and
    // property access, rather than trying to interpret arbitrary loader code.
    if (ts.isIdentifier(node) && node.text === 'require') {
      throw new Error(`Unsupported bootstrap import loader: ${filePath}`);
    }
    if (
      (ts.isImportDeclaration(node) || ts.isExportDeclaration(node)) &&
      node.moduleSpecifier
    ) {
      if (!ts.isStringLiteral(node.moduleSpecifier))
        throw new Error(`Nonliteral bootstrap import: ${filePath}`);
      validate(node.moduleSpecifier.text);
    }
    if (
      ts.isImportTypeNode(node) &&
      ts.isLiteralTypeNode(node.argument) &&
      ts.isStringLiteral(node.argument.literal)
    )
      validate(node.argument.literal.text);
    if (
      ts.isImportEqualsDeclaration(node) &&
      ts.isExternalModuleReference(node.moduleReference)
    ) {
      const expression = node.moduleReference.expression;
      if (!expression || !ts.isStringLiteral(expression))
        throw new Error(`Nonliteral bootstrap import: ${filePath}`);
      validate(expression.text);
    }
    if (
      ts.isCallExpression(node) &&
      (node.expression.kind === ts.SyntaxKind.ImportKeyword ||
        (ts.isIdentifier(node.expression) &&
          node.expression.text === 'require'))
    ) {
      const argument = node.arguments[0];
      if (
        node.arguments.length !== 1 ||
        !argument ||
        !ts.isStringLiteral(argument)
      )
        throw new Error(`Nonliteral bootstrap import: ${filePath}`);
      validate(argument.text);
    }
    ts.forEachChild(node, (child) => {
      visit(child);
    });
  };
  visit(parsed);
}

function assertMode(
  mode: string,
): asserts mode is WorkflowBootstrapHostGenerationMode {
  if (mode !== '--check' && mode !== '--write')
    throw new Error(
      'Usage: generate-workflow-bootstrap-host.ts [--check|--write]',
    );
}

if (import.meta.main) {
  const mode = process.argv[2] ?? '--check';
  assertMode(mode);
  generateWorkflowBootstrapHost(DEFAULT_REPOSITORY_ROOT, mode);
}
