import assert from 'node:assert/strict';
import crypto from 'node:crypto';
import fs from 'node:fs';
import os from 'node:os';
import path from 'node:path';
import test from 'node:test';
import { captureGovernanceSource } from '../src/modules/governance-intake/governance-intake.ts';
import {
  createWorkItem,
  inspectWorkRegistryProjectionStatus,
  renderWorkRegistry,
  validateWorkRegistryProjections,
} from '../src/modules/governance-intake/work-registry.ts';

test('registry service renders readable backlog lanes and recomputes drift without changing inventory', () => {
  const root = fs.mkdtempSync(
    path.join(os.tmpdir(), 'registry-projection-golden-'),
  );
  try {
    fs.mkdirSync(path.join(root, 'workflow'));
    for (const name of ['config.json', 'repository-consumer.json']) {
      fs.copyFileSync(
        new URL(`../../../workflow/${name}`, import.meta.url),
        path.join(root, 'workflow', name),
      );
    }
    createWorkItem(
      root,
      {
        schemaVersion: 1,
        kind: 'bug',
        lane: 'later',
        title: 'Exact projection',
        summary: 'Unicode 原文\nsecond line',
        sourceRefs: [],
      },
      {
        now: () => '2026-09-08T00:00:00.000Z',
        createId: () => 'WORK-01K39R0V000000000000000002',
      },
    );
    const output = renderWorkRegistry(root);
    assert.equal(
      fs.readFileSync(output.backlogPath, 'utf8'),
      [
        '# Backlog',
        '',
        '<!-- Generated by jigwright work-item render. -->',
        '',
        '## Later',
        '',
        '### Exact projection',
        '',
        '- Kind: bug',
        '- Stage: inbox',
        '',
        'Unicode 原文\nsecond line',
        '',
      ].join('\n'),
    );
    // The machine inventory remains byte-identical to the original projection.
    for (const [file, expected] of [
      [
        output.inventoryPath,
        'c033172a05d2e0484b0135b031315c65ae8d096ae5db2bdcfd40dbe98aa4b463',
      ],
    ]) {
      assert.equal(
        crypto
          .createHash('sha256')
          .update(fs.readFileSync(file!))
          .digest('hex'),
        expected,
      );
    }
    assert.equal(
      inspectWorkRegistryProjectionStatus(root).every(
        (row) => row.state === 'current',
      ),
      true,
    );
    fs.appendFileSync(output.backlogPath, '\nchanged');
    assert.equal(
      inspectWorkRegistryProjectionStatus(root).find(
        (row) => row.id === 'registry.backlog',
      )?.state,
      'drifted',
    );
    assert.throws(() => validateWorkRegistryProjections(root), {
      code: 'WORK_REGISTRY_PROJECTION_DRIFT',
    });
    const staleHistory = path.join(root, 'docs/work-history/2025.md');
    fs.mkdirSync(path.dirname(staleHistory), { recursive: true });
    fs.writeFileSync(staleHistory, 'stale');
    assert.equal(
      inspectWorkRegistryProjectionStatus(root).find((row) =>
        row.path.endsWith('/2025.md'),
      )?.state,
      'unexpected',
    );
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});

test('backlog projects exact Source wording, kind, and lane without opaque identities', () => {
  const root = fs.mkdtempSync(path.join(os.tmpdir(), 'registry-readable-'));
  try {
    fs.mkdirSync(path.join(root, 'workflow'));
    for (const name of ['config.json', 'repository-consumer.json']) {
      fs.copyFileSync(
        new URL(`../../../workflow/${name}`, import.meta.url),
        path.join(root, 'workflow', name),
      );
    }
    const wording =
      '  Keep 原話 exactly.\n\nSecond line, with trailing spaces.  \n';
    const source = captureGovernanceSource(root, {
      semanticAuthor: 'maintainer',
      capturedBy: 'jigwright',
      capturedAt: '2026-09-08T00:00:00.000Z',
      contextRef: 'direct-human:readable-backlog',
      text: wording,
      supersedes: null,
    }).source;
    createWorkItem(
      root,
      {
        schemaVersion: 1,
        kind: 'feature',
        lane: 'now',
        title: 'Readable requirement',
        summary: `Interpret and disposition linked Sources: ${source.id}.`,
        sourceRefs: [source.id],
      },
      {
        now: () => '2026-09-08T00:00:00.000Z',
        createId: () => 'WORK-01K39R0V000000000000000003',
      },
    );
    createWorkItem(
      root,
      {
        schemaVersion: 1,
        kind: 'research',
        lane: null,
        title: 'Explore later',
        summary: 'Unreviewed observation',
        sourceRefs: [],
      },
      {
        now: () => '2026-09-08T00:00:00.000Z',
        createId: () => 'WORK-01K39R0V000000000000000004',
      },
    );
    const output = renderWorkRegistry(root);
    const backlog = fs.readFileSync(output.backlogPath, 'utf8');
    assert.ok(backlog.includes('## Now\n'));
    assert.ok(backlog.includes('## Unprioritized\n'));
    assert.ok(backlog.indexOf('## Now') < backlog.indexOf('## Unprioritized'));
    assert.ok(backlog.includes('- Kind: feature\n'));
    assert.ok(backlog.includes('- Kind: research\n'));
    const projected = backlog
      .split('\n')
      .filter((line) => /^>(?: |$)/.test(line))
      .map((line) => line.replace(/^> ?/, ''))
      .join('\n');
    assert.equal(projected, wording);
    assert.doesNotMatch(backlog, /(?:SRC|WORK|FND)-[A-Za-z0-9]+/);
    validateWorkRegistryProjections(root);
  } finally {
    fs.rmSync(root, { recursive: true, force: true });
  }
});
