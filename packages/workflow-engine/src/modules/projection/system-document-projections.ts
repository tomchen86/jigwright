/**
 * Projects the contract map, proof coverage and original requirements as readable text.
 *
 * Invariants:
 * - Source wording is read from the inspection; projections never create canonical facts.
 * - Missing and stale proof remain visible and are never presented as passing tests.
 */
import path from 'node:path';
import type { GovernanceSourceAlias } from '../governance-intake/source-aliases.ts';
import type { SystemDocumentInspection } from '../source/system-documents.ts';
import type { ProjectionBinding } from './projection-service.ts';

export function systemDocumentProjectionBindings(
  report: SystemDocumentInspection,
  aliases: Readonly<Record<string, GovernanceSourceAlias>> = {},
): ProjectionBinding[] {
  const opening = (title: string) => [
    `# ${title}`,
    '',
    '<!-- Generated by jigwright documents render. -->',
    '',
  ];
  const specMap = [
    ...opening('Specification map'),
    '| Module | Governing contract | Ownership |',
    '| --- | --- | --- |',
    ...(report.modules ?? []).map((module) => {
      const spec = report.specs.find((spec) => spec.path === module.specPath);
      return `| ${cell(module.path)} | ${spec ? link(spec.title, spec.path) : 'Missing contract'} | ${module.specPath ? (path.posix.dirname(module.specPath) === module.path ? 'Local' : 'Inherited') : 'Uncovered'} |`;
    }),
    '',
    '## Contract inventory',
    '',
    '| Directory | Contract | Requirements | Scenarios |',
    '| --- | --- | ---: | ---: |',
    ...report.specs.map(
      (spec) =>
        `| ${cell(path.posix.dirname(spec.path))} | ${link(spec.title, spec.path)} | ${spec.requirements.length} | ${spec.requirements.reduce((total, requirement) => total + requirement.scenarios.length, 0)} |`,
    ),
    '',
  ].join('\n');
  const linkedSources = new Set(
    report.specs.flatMap((spec) =>
      spec.requirements.flatMap((requirement) => [
        ...requirement.sources,
        ...requirement.scenarios.flatMap((scenario) => scenario.sources),
      ]),
    ),
  );
  const uncoveredSources = [...report.sources.values()]
    .filter((source) => !linkedSources.has(source.id))
    .sort((left, right) => left.id.localeCompare(right.id));
  const uncoveredDirectories = (
    report.directories ??
    report.modules ??
    []
  ).filter((directory) => directory.specPath === null);
  const requirementsWithoutSources = report.specs.flatMap((spec) =>
    spec.requirements
      .filter((requirement) => requirement.sources.length === 0)
      .map((requirement) => ({ spec, requirement })),
  );
  const coverage = [
    ...opening('Documentation coverage'),
    '## Sources without a linked contract',
    '',
    'Recorded wording with no requirement or scenario citation in the current colocated contracts.',
    '',
    '| Original wording |',
    '| --- |',
    ...(uncoveredSources.length
      ? uncoveredSources.map(
          (source) =>
            `| ${source.text.split(/\r?\n/).map(cell).join('<br>')} |`,
        )
      : ['| None. |']),
    '',
    '## Directories without a governing contract',
    '',
    'Source directories without any containing spec.md. An inherited package or root contract counts as ownership; generated and test directories are excluded.',
    '',
    '| Directory |',
    '| --- |',
    ...(uncoveredDirectories.length
      ? uncoveredDirectories.map(
          (directory) => `| ${link(directory.path, directory.path)} |`,
        )
      : ['| None. |']),
    '',
    '## Requirements without Sources',
    '',
    '| Requirement | Contract |',
    '| --- | --- |',
    ...(requirementsWithoutSources.length
      ? requirementsWithoutSources.map(
          ({ spec, requirement }) =>
            `| ${cell(requirement.title)} | ${link(spec.title, spec.path)} |`,
        )
      : ['| None. | None. |']),
    '',
    '## Module and package documentation',
    '',
    'Header counts cover source files in each scope; package rows include their modules. Two-part headers contain both a responsibility and at least one invariant. Missing local documents and headers are documentation gaps, not additional gates.',
    '',
    '| Scope | Kind | Contract | Ownership | README | Headers | Two-part headers |',
    '| --- | --- | --- | --- | --- | ---: | ---: |',
    ...(report.documentation ?? []).map((scope) => {
      const owner = report.specs.find((spec) => spec.path === scope.specPath);
      return `| ${cell(scope.path)} | ${scope.kind} | ${owner ? link(owner.title, owner.path) : 'Missing'} | ${scope.specPath ? (path.posix.dirname(scope.specPath) === scope.path ? 'Local' : 'Inherited') : 'Uncovered'} | ${scope.readmePath ? link('Present', scope.readmePath) : 'Missing'} | ${scope.headers}/${scope.files} | ${scope.invariantHeaders}/${scope.files} |`;
    }),
    '',
    '## Scenario coverage',
    '',
    '| Requirement / scenario | Covers | Test | Result |',
    '| --- | --- | --- | --- |',
    ...report.scenarios.map(
      (scenario) =>
        `| ${link(`${scenario.requirement} / ${scenario.scenario}`, scenario.specPath)} | ${cell(scenario.covers ?? 'Missing binding')} | ${scenario.testPath ? link(scenario.testName ?? 'Missing test name', scenario.testPath) : 'Missing test'} | ${scenario.outcome} |`,
    ),
    '',
  ].join('\n');
  const named = new Set(
    Object.values(aliases).flatMap((alias) => alias.sourceRefs),
  );
  const requirements = [
    ...opening('Requirements'),
    ...Object.values(aliases).flatMap((alias) =>
      section(alias.title, alias.sourceRefs),
    ),
    ...[...report.sources.values()]
      .filter((source) => !named.has(source.id))
      .flatMap((source) =>
        section(
          source.text.split('\n').find((line) => line.trim()) ?? 'Requirement',
          [source.id],
        ),
      ),
  ].join('\n');
  return [
    binding('documents.spec-map', 'docs/SPEC_MAP.md', specMap),
    binding('documents.coverage', 'docs/COVERAGE.md', coverage),
    binding('documents.requirements', 'docs/REQUIREMENTS.md', requirements),
  ];

  function section(title: string, refs: readonly string[]): string[] {
    const contracts = report.specs.flatMap((spec) =>
      spec.requirements
        .filter((requirement) =>
          requirement.sources.some((ref) => refs.includes(ref)),
        )
        .map((requirement) => `- ${link(requirement.title, spec.path)}`),
    );
    return [
      `## ${title.replaceAll('\n', ' ')}`,
      '',
      ...refs.flatMap((ref) => {
        const source = report.sources.get(ref);
        return source
          ? [
              ...source.text
                .split('\n')
                .map((line) => (line === '' ? '>' : `> ${line}`)),
              '',
            ]
          : ['Source wording is unavailable; run documents validate.', ''];
      }),
      ...(contracts.length > 0 ? contracts : ['No linked contract yet.']),
      '',
    ];
  }
}

function binding(
  id: ProjectionBinding['id'],
  target: string,
  content: string,
): ProjectionBinding {
  return { id, source: () => [{ path: target, content }] };
}
function cell(value: string): string {
  return value
    .replaceAll('&', '&amp;')
    .replaceAll('<', '&lt;')
    .replaceAll('>', '&gt;')
    .replaceAll('|', '\\|')
    .replaceAll('\n', ' ');
}
function link(label: string, target: string): string {
  return `[${cell(label).replaceAll('[', '\\[').replaceAll(']', '\\]')}](${encodeURI(path.posix.relative('docs', target))})`;
}
