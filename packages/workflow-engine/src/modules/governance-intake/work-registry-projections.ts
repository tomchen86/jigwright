/** Pure readable backlog/history rendering and projection drift policy. */
import type { WorkItemV1, WorkItemLaneV1 } from './work-registry-contracts.ts';
import { workflowError, ExitCode } from '../../foundation/errors/errors.ts';
export function compareWorkItems(left: WorkItemV1, right: WorkItemV1): number {
  const lanes: Record<Exclude<WorkItemLaneV1, null> | 'none', number> = {
    now: 0,
    next: 1,
    later: 2,
    icebox: 3,
    none: 4,
  };
  return (
    lanes[left.lane ?? 'none'] - lanes[right.lane ?? 'none'] ||
    left.id.localeCompare(right.id)
  );
}
export function closedWorkItemsByYear(
  items: readonly WorkItemV1[],
): Map<string, WorkItemV1[]> {
  const byYear = new Map<string, WorkItemV1[]>();
  for (const item of items.filter(
    (candidate) => candidate.stage === 'closed',
  )) {
    const year = item.closure!.at.slice(0, 4);
    byYear.set(year, [...(byYear.get(year) ?? []), item]);
  }
  return byYear;
}
export function renderHistoryProjection(
  year: string,
  closed: readonly WorkItemV1[],
): string {
  return [
    `# Work history ${year}`,
    '',
    '<!-- Generated by jigwright work-item render. -->',
    '',
    ...[...closed]
      .sort(compareWorkItems)
      .map(
        (item) =>
          `- **${item.id} — ${item.title}** (${item.closure!.outcome}${item.closure!.changeId ? `; ${item.closure!.changeId}` : ''})`,
      ),
    '',
  ].join('\n');
}
export function projectionDrift(message: string) {
  return workflowError(
    'WORK_REGISTRY_PROJECTION_DRIFT',
    message,
    ExitCode.verification,
    { recovery: 'Run `pnpm workflow work-item render --json`.' },
  );
}
export function backlogWorkItems(items: readonly WorkItemV1[]): WorkItemV1[] {
  return items.filter((item) => item.stage !== 'closed').sort(compareWorkItems);
}
export function renderBacklogProjection(
  sourceTexts: ReadonlyMap<string, readonly string[]>,
  items: readonly WorkItemV1[],
): string {
  const open = items
    .filter((item) => item.stage !== 'closed')
    .sort(compareWorkItems);
  const titles = new Map(items.map((item) => [item.id, item.title]));
  const lanes = [
    ['now', 'Now'],
    ['next', 'Next'],
    ['later', 'Later'],
    ['icebox', 'Icebox'],
    [null, 'Unprioritized'],
  ] as const;
  return [
    '# Backlog',
    '',
    '<!-- Generated by jigwright work-item render. -->',
    '',
    ...(open.length === 0
      ? ['No open Work Items.', '']
      : lanes.flatMap(([lane, label]) => {
          const group = open.filter((item) => item.lane === lane);
          return group.length === 0
            ? []
            : [
                `## ${label}`,
                '',
                ...group.flatMap((item) => [
                  `### ${item.title}`,
                  '',
                  `- Kind: ${item.kind}`,
                  `- Stage: ${item.stage}`,
                  ...(item.blockedBy.length > 0
                    ? [
                        `- Blocked by: ${item.blockedBy.map((id) => titles.get(id) ?? 'Unresolved work item').join(', ')}`,
                      ]
                    : []),
                  '',
                  ...(item.sourceRefs.length === 0
                    ? [item.interpretation.summary, '']
                    : item.sourceRefs.flatMap((_sourceRef, index) => [
                        ...sourceTexts
                          .get(item.id)!
                          [index]!.split('\n')
                          .map((line) => (line === '' ? '>' : `> ${line}`)),
                        '',
                      ])),
                ]),
              ];
        })),
  ].join('\n');
}
